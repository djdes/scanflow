import { config } from '../config';

/**
 * Ссылка на карточку накладной для внешних получателей (Telegram, почта).
 *
 * ВАЖНО: путь именно `/app.html`. Кабинет — отдельная страница, а по корню `/`
 * отдаётся лендинг, который про хеш-маршруты ничего не знает. Раньше ссылки
 * строились как `${base}/#/invoices/<id>` и открывали рекламную страницу вместо
 * накладной — для КАЖДОГО уведомления, а не только для склеенных страниц.
 *
 * Собрано в одном месте, чтобы формат нельзя было разъехать по четырём файлам,
 * как было до этого.
 */
export function invoiceUrl(id: number): string {
  return `${config.publicBaseUrl}/app.html#/invoices/${id}`;
}
