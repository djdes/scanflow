import { describe, expect, it } from 'vitest';
import { plural, rub } from '../../src/utils/ru';

describe('русские слова в текстах для людей', () => {
  it('склоняет по числу, а не «строк(и)»', () => {
    const f = (n: number) => plural(n, 'строка', 'строки', 'строк');
    expect([1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 101, 111].map(f)).toEqual(
      ['строка', 'строки', 'строки', 'строк', 'строк', 'строк', 'строк', 'строка', 'строки', 'строк', 'строка', 'строк']);
    expect(f(0)).toBe('строк');
  });

  it('пишет деньги с разрядами и запятой, а не «50000.00»', () => {
    expect(rub(50000).replace(/\s/g, ' ')).toBe('50 000 ₽');
    expect(rub(1234.5).replace(/\s/g, ' ')).toBe('1 234,5 ₽');
  });
});
