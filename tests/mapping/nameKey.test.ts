import { describe, it, expect } from 'vitest';
import { itemNameKey, extractAttrs, attrsConflict } from '../../src/mapping/nameKey';

describe('itemNameKey — один ключ на товар, а не на написание', () => {
  it('скобки, пробелы, регистр и запятая в числе не важны', () => {
    const k = itemNameKey('Капуста морская(3кг)');
    expect(itemNameKey('Капуста морская (3 кг)')).toBe(k);
    expect(itemNameKey('КАПУСТА МОРСКАЯ 3кг')).toBe(k);
  });

  it('порядок слов не важен', () => {
    expect(itemNameKey('Огурчики 9-12 маринованные 7,5кг'))
      .toBe(itemNameKey('Огурчики маринованные 7,5 кг 9-12'));
  });

  it('логистические счётчики упаковки и ГОСТ отбрасываются', () => {
    expect(itemNameKey('Маслины 300г без косточки 1/12')).toBe(itemNameKey('Маслины 300г без косточки'));
    expect(itemNameKey('Горбуша нат. 240г*24 ГОСТ')).toBe(itemNameKey('Горбуша нат. 240г'));
    expect(itemNameKey('Контейнер ПП К-139, 500мл (х50/500)')).toBe(itemNameKey('Контейнер ПП К-139 500мл'));
  });

  it('разные размеры и объёмы — разные товары', () => {
    expect(itemNameKey('Контейнер 750мл')).not.toBe(itemNameKey('Контейнер 500мл'));
    expect(itemNameKey('Вода 1,5л')).not.toBe(itemNameKey('Вода 0,5л'));
  });

  it('ё = е, латиница внутри русского слова = кириллица', () => {
    expect(itemNameKey('Зелёный горошек')).toBe(itemNameKey('Зеленый горошек'));
    expect(itemNameKey('Cметана 20%')).toBe(itemNameKey('Сметана 20%'));
  });

  it('пустое имя — пустой ключ', () => {
    expect(itemNameKey('')).toBe('');
    expect(itemNameKey('  ,. ')).toBe('');
  });
});

describe('extractAttrs', () => {
  it('объёмы, массы, габариты, коды', () => {
    const a = extractAttrs('Контейнер средний без крыш. прямоуг. ПП К-139, 750мл 139х102х86мм цвет прозр. СТП (х50/500)');
    expect(a.volumesMl).toEqual([750]);
    expect(a.dims).toEqual(['139x102x86']);
    expect(a.codes).toContain('к139');
  });

  it('калибр: диапазон и дробь приводятся к одному виду', () => {
    expect(extractAttrs('Камбала потрошеная 300-500г').calibers).toEqual(['300-500']);
    expect(extractAttrs('Камбала 300/500').calibers).toEqual(['300-500']);
    expect(extractAttrs('Креветка Ваннамей 21/25').calibers).toEqual(['21-25']);
    expect(extractAttrs('Маслины 1/12').calibers).toEqual([]);
  });

  it('жирность и размеры перчаток', () => {
    expect(extractAttrs('Майонез Провансаль 67% 9,6кг').fats).toEqual(['67']);
    expect(extractAttrs('Перчатки нитриловые (M) цвет Голубой').sizes).toEqual(['m']);
    expect(extractAttrs('Перчатки нитриловые (Черные) М 100шт/упак').sizes).toEqual(['m']);
    expect(extractAttrs('Сметана с 20%').sizes).toEqual([]);
  });

  it('счёт «240г*24» — не габарит, «32*40» — габарит', () => {
    expect(extractAttrs('Горбуша 240г*24').dims).toEqual([]);
    expect(extractAttrs('Фасовка СУПЕР ПАК 32*40 1400гр').dims).toEqual(['32x40']);
  });
});

describe('attrsConflict', () => {
  const c = (a: string, b: string) => attrsConflict(extractAttrs(a), extractAttrs(b));

  it('разные объёмы/габариты — конфликт', () => {
    expect(c('Контейнер К-139, 750мл 139х102х86мм', 'Контейнер К-139, 500мл 139х102х56мм')).not.toBeNull();
  });

  it('разные размеры перчаток — конфликт', () => {
    expect(c('Перчатки нитриловые (M)', 'Перчатки нитриловые S 200шт')).not.toBeNull();
  });

  it('разная жирность — конфликт, одинаковая — нет', () => {
    expect(c('Сметана 20% 3кг', 'Сметана 15%')).not.toBeNull();
    expect(c('Майонез 67% 10л/9,6кг', 'Майонез МЖК 67%')).toBeNull();
  });

  it('атрибут только с одной стороны — не конфликт', () => {
    expect(c('Капуста морская 3кг', 'Капуста морская')).toBeNull();
    expect(c('Масло подсолнечное 1л 1/15', 'Масло подсолнечное')).toBeNull();
  });

  it('калибр 300-500г совпадает с 300/500', () => {
    expect(c('Камбала потрошеная 300-500г', 'Камбала 300/500')).toBeNull();
  });

  it('разные коды моделей — конфликт', () => {
    expect(c('Подложка Е-21, АВ (225*100*20)мм', 'Подложка D-21 А (225*135*20)мм')).not.toBeNull();
  });

  it('«D=38» = «D38», «(х150)» — не артикул, «1З2» — опечатка OCR в «132»', () => {
    expect(c('ПЭТ бутылка 0.33л черная крышка D38 (150)', 'Бутылка ПЭТ с черной крыш. 0.33л D=38мм (х150)')).toBeNull();
    expect(c('Контейнер низкий ПП 750мл 179х1З2х46мм', 'Контейнер низкий ПП 750мл 179х132х46мм')).toBeNull();
  });

  it('OCR «З» вместо «3» в начале числа и габарит-префикс — не конфликт', () => {
    expect(c('Молоко З,2% дешевое', 'Молоко 3,2% дешевое')).toBeNull();
    expect(c('Контейнер СпК-115, З50мл D=115мм', 'Контейнер СпК-115, 350мл D=115мм')).toBeNull();
    expect(c('Крышка ПП 139х102 прозр.', 'Крышка ПП К-139К 139х102х9мм прозр.')).toBeNull();
    expect(c('Крышка ПП круглая D115 прозр.', 'Крышка к конт. круглая ПП СпК-115К D=115мм')).toBeNull();
  });

  it('настоящие различия остаются конфликтом', () => {
    expect(c('Мусорные мешки 180л ПВД 90*120см', 'Мусорные мешки 180л ПВД 90*100см')).not.toBeNull();
    expect(c('Бутылка ПЭТ 0,3л d=38мм', 'Бутылка ПЭТ 0.33л D=38мм')).not.toBeNull();
    expect(c('Контейнер ПП К-187 470мл', 'Контейнер ПП К-139 470мл')).not.toBeNull();
  });

  it('несколько масс: достаточно совпадения одной (нетто 9,6 кг)', () => {
    expect(c('Майонез 67% 10л/9,6кг', 'Майонез 9,6кг')).toBeNull();
  });
});
